/**
 * Fast Lookup Map & Alias Index built once on initialization
 */
const ALIAS_INDEX = new Map();
const ID_INDEX = new Map();

// Populate indexes
INDIAN_FOOD_DATABASE.forEach((item) => {
  ID_INDEX.set(item.id, item);
  
  // Index primary name
  const cleanName = item.name.toLowerCase().trim();
  ALIAS_INDEX.set(cleanName, item);

  // Index aliases
  if (Array.isArray(item.aliases)) {
    item.aliases.forEach((alias) => {
      ALIAS_INDEX.set(alias.toLowerCase().trim(), item);
    });
  }

  // Index local names
  if (Array.isArray(item.localNames)) {
    item.localNames.forEach((ln) => {
      ALIAS_INDEX.set(ln.toLowerCase().trim(), item);
    });
  }
});

/**
 * Find food item by query using exact alias, prefix, or token containment
 */
export function searchIndianFoodDatabase(query) {
  if (!query || typeof query !== 'string') return null;
  const q = query.toLowerCase().trim();

  // 1. Direct match on key or alias
  if (ALIAS_INDEX.has(q)) {
    return ALIAS_INDEX.get(q);
  }

  // 2. Direct ID check
  if (ID_INDEX.has(q)) {
    return ID_INDEX.get(q);
  }

  // 3. Normalized search (strip extra spaces and punctuation)
  const normalized = q.replace(/[^a-z0-9 ]/g, ' ').replace(/\s+/g, ' ').trim();
  if (ALIAS_INDEX.has(normalized)) {
    return ALIAS_INDEX.get(normalized);
  }

  // 4. Token overlap search
  for (const [alias, item] of ALIAS_INDEX.entries()) {
    if (alias === normalized || normalized.startsWith(alias) || alias.startsWith(normalized)) {
      return item;
    }
  }

  // 5. Containment check
  for (const [alias, item] of ALIAS_INDEX.entries()) {
    if (alias.length >= 3 && (normalized.includes(alias) || alias.includes(normalized))) {
      return item;
    }
  }

  return null;
}
